import { showNotice } from './dialog.js';

export const INTRO_GUIDE = `あなたは鬼灯栞。母の死への復讐のため、殺人計画に加わった共犯者です。
仲間と役割を分担する計画は、館で現実になろうとしています。

探偵の追及をしのぎながら、計画や館の違和感を調べてください。集めた証拠と言葉をもとに、計画を続けるか、真実を話すかを選ぶ物語です。

本文をクリック／タップすると読み進めます。PCでは Space／Enter も使えます。文字の表示中は、まず全文を表示します。
選択肢はボタンを押して決定します。「遊び方」から、いつでも説明を読み返せます。`;

export const PLAY_GUIDE = `【あなたの立場と目的】
あなたは殺人計画の共犯者・鬼灯栞です。探偵の追及をしのぎ、計画や館の違和感を調べながら、計画を続けるか、真実を話すかを選びます。発言と集めた証拠が、その後の選択肢や結末に影響します。

【基本操作】
本文のクリック／タップ、Space／Enter：続きを読む（表示中は全文表示）。選択肢はボタンで決定。
手帳：証拠・手掛かり・証言を確認。ログ：直前までの会話を読み返す。
セーブ／ロード：進行を保存／再開。特殊パート中のセーブは、そのパートの開始時点から再開します。
オート：自動送り。スキップ：既読の本文を早送り（範囲は設定で変更可）。
PCのショートカット：S セーブ／L ロード／N 手帳／A オート／Ctrl スキップ。Esc で開いている説明やメニューを閉じます。スマートフォンは横向きで遊べます。

【自由行動】
行動の内容と影響を読み、行動ボタンを押すと開始します。1つの行動で残り回数を1消費します。読む・考える・見取り図を見るだけでは時間は進みません。すべてを調べる時間はありません。
手掛かりは後の推理、反論札は尋問への応答に使います。「残り0」まで行動するか「自由行動を切り上げる」で物語が進みます。

【数値と証拠の意味】
疑惑：あなたへの疑い。確信：探偵が推理を信じる強さ。高いほど追及が厳しくなります。
知りすぎ：共犯者しか知らない情報を口にした危険。強い反論でも、知った理由を説明できなければ疑われます。
🕯 過去／📜 計画／👁 生存：集めた手掛かりの分類と件数です。得点ではありません。

【推理パート】
反論では、主張を読み、応答と反論札を選んで確定します。手毬唄ボードでは唄と事件を対応させます。共同推理では証拠で主張の矛盾を崩します。各画面の手順に沿って選び、決定ボタンで確定してください。`;

export function showPlayGuide({ mount, intro = false } = {}) {
  return showNotice({ mount, title: intro ? 'この物語で、あなたが選ぶこと' : '遊び方・目的', body: intro ? INTRO_GUIDE : PLAY_GUIDE, okLabel: intro ? '栞として物語を始める' : 'ゲームに戻る' });
}
